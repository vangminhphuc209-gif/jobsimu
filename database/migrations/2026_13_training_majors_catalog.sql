-- Training Majors & Institution Source Catalog upgrade (HNV dataset integration)
-- Additive and idempotent migration for MySQL 5.7+ / MariaDB 10.x.
-- Preserves all legacy tables in database/schema.sql and existing career-admissions tables.
-- Separates source availability, JobSimu description workflow, official code verification with evidence,
-- mapping review, per-source/year admission status, and initial source warnings vs open review issues.

CREATE TABLE IF NOT EXISTS `major_fields` (
    `id` VARCHAR(32) PRIMARY KEY,
    `name` VARCHAR(200) NOT NULL,
    `normalized_name` VARCHAR(200) NOT NULL,
    `source_system` VARCHAR(40) NOT NULL DEFAULT 'hnv',
    `source_url` VARCHAR(500) NOT NULL,
    `retrieved_at` VARCHAR(64) NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX `idx_major_fields_norm` (`normalized_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `major_subgroups` (
    `id` VARCHAR(32) PRIMARY KEY,
    `field_id` VARCHAR(32) NOT NULL,
    `name` VARCHAR(200) NOT NULL,
    `normalized_name` VARCHAR(200) NOT NULL,
    `source_system` VARCHAR(40) NOT NULL DEFAULT 'hnv',
    `source_url` VARCHAR(500) NOT NULL,
    `retrieved_at` VARCHAR(64) NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX `idx_major_subgroups_field` (`field_id`),
    INDEX `idx_major_subgroups_norm` (`normalized_name`),
    CONSTRAINT `fk_major_subgroup_field` FOREIGN KEY (`field_id`) REFERENCES `major_fields` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

