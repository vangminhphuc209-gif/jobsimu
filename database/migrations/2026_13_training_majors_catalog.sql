CREATE TABLE IF NOT EXISTS `major_review_issues` (
    `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `major_id` VARCHAR(120) NOT NULL,
    `issue_code` VARCHAR(60) NOT NULL,
    `issue_category` VARCHAR(40) NOT NULL,
    `origin` VARCHAR(30) NOT NULL DEFAULT 'initial_source',
    `status` VARCHAR(30) NOT NULL DEFAULT 'open',
    `detail_note` TEXT NULL,
    `resolution_note` TEXT NULL,
    `resolved_by` INT UNSIGNED NULL,
    `resolved_at` DATETIME NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY `uk_mri_major_issue` (`major_id`, `issue_code`),
    INDEX `idx_mri_status_code` (`status`, `issue_code`),
