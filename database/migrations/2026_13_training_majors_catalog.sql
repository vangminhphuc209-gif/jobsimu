    `official_institution_id` INT UNSIGNED NULL,
    `source_system` VARCHAR(40) NOT NULL DEFAULT 'hnv',
    `verification_status` VARCHAR(80) NOT NULL DEFAULT 'unmerged_source_url',
    `retrieved_at` VARCHAR(64) NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
