    `review_note` TEXT NULL,
    `reviewed_by` INT UNSIGNED NULL,
    `reviewed_at` DATETIME NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY `uk_tm_existing_major` (`training_major_id`, `existing_major_id`),
    INDEX `idx_tmm_status` (`mapping_status`),
    CONSTRAINT `fk_tmm_training_major` FOREIGN KEY (`training_major_id`) REFERENCES `training_majors` (`id`) ON DELETE CASCADE,
